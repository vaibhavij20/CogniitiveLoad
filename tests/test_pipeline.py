W, H = 640, 480


def rot(yaw=0.0, pitch=0.0, roll=0.0):
    y, p, r = map(math.radians, (yaw, pitch, roll))
    rx = np.array([[1, 0, 0], [0, math.cos(p), -math.sin(p)], [0, math.sin(p), math.cos(p)]])
    ry = np.array([[math.cos(y), 0, math.sin(y)], [0, 1, 0], [-math.sin(y), 0, math.cos(y)]])
    rz = np.array([[math.cos(r), -math.sin(r), 0], [math.sin(r), math.cos(r), 0], [0, 0, 1]])
    return rz @ ry @ rx


def synthetic_face(yaw=0.0, pitch=0.0, eye_open=1.0, iris_shift=0.0, offset=(0, 0)):
    """478x2 landmark array. Image y points down, so the model is flipped (rotation of 180 about x)."""
    pts = np.full((478, 2), [W / 2, H / 2], dtype=float)
    flip = np.diag([1, -1, -1])                       # model y-up -> camera y-down, facing camera
    r = rot(yaw, pitch) @ flip
    model = np.array(config.POSE_MODEL_3D)
    cam = np.array([[W, 0, W / 2], [0, W, H / 2], [0, 0, 1]], float)
    tvec = np.array([0, 0, 500.0])
    proj = (cam @ ((r @ model.T).T + tvec).T).T
    proj = proj[:, :2] / proj[:, 2:]
    for idx, p in zip(config.POSE_LANDMARKS, proj):
        pts[idx] = p + offset

    def eye(ids, iris_ids, cx, cy):
        half_w, half_h = 20, 8 * eye_open
        e = [(cx - half_w, cy), (cx - 7, cy - half_h), (cx + 7, cy - half_h),
             (cx + half_w, cy), (cx + 7, cy + half_h), (cx - 7, cy + half_h)]
        for i, p in zip(ids, e):
            pts[i] = np.array(p) + offset
        for i in iris_ids:
            pts[i] = np.array([cx + iris_shift * 2 * half_w, cy]) + offset
    # eyes are built around the projected outer corners (33, 263) so pose and EAR stay consistent
    lc, rc = proj[config.POSE_LANDMARKS.index(33)], proj[config.POSE_LANDMARKS.index(263)]
    eye(config.LEFT_EYE, config.LEFT_IRIS, lc[0] + 20, lc[1])
    eye(config.RIGHT_EYE, config.RIGHT_IRIS, rc[0] - 20, rc[1])
    return pts


class TestSignals(unittest.TestCase):
    def test_ear_open_vs_closed(self):
        open_ear = signals.eye_aspect_ratio(synthetic_face()[config.LEFT_EYE])
        closed_ear = signals.eye_aspect_ratio(synthetic_face(eye_open=0.1)[config.LEFT_EYE])
        self.assertGreater(open_ear, config.EAR_OPEN)
        self.assertLess(closed_ear, config.EAR_CLOSE)

    def test_blink_counting_with_hysteresis(self):
        b = signals.BlinkDetector()
        seq = [0.3, 0.1, 0.1, 0.23, 0.1, 0.3, 0.3, 0.1, 0.3]   # 0.23 is not re-open -> 2 blinks
        for i, e in enumerate(seq):
            b.update(e, now=i * 0.1)
        self.assertEqual(b.count, 2)

    def test_blink_window_expires(self):
        b = signals.BlinkDetector()
        b.update(0.1, now=0)
        b.update(0.3, now=0.2)
        self.assertEqual(b.update(0.3, now=61), 0)

    def test_blink_rate_per_minute(self):
        b = signals.BlinkDetector()
        r = 0
        for i in range(30 * 30):                     # 30 s at 30 fps, one blink every 3 s
            r = b.update(0.1 if i % 90 == 0 else 0.3, now=i / 30)
        self.assertAlmostEqual(r, 20, delta=2)

    def test_gaze_centre_and_side(self):
        f0, f1 = synthetic_face(), synthetic_face(iris_shift=0.3)
        g0 = signals.gaze_offset(f0[config.LEFT_EYE], f0[config.LEFT_IRIS].mean(0))
        g1 = signals.gaze_offset(f1[config.LEFT_EYE], f1[config.LEFT_IRIS].mean(0))
        self.assertAlmostEqual(g0, 0.0, places=3)
        self.assertAlmostEqual(g1, 0.3, places=2)

    def test_head_pose_recovers_known_angles(self):
        for yaw, pitch in [(0, 0), (20, 0), (-30, 0), (0, 15), (25, -10)]:
            f = synthetic_face(yaw=yaw, pitch=pitch)
            y, p, _ = signals.head_pose(f[config.POSE_LANDMARKS], W, H)
            self.assertAlmostEqual(abs(y), abs(yaw), delta=3, msg=f"yaw {yaw}")
            self.assertAlmostEqual(abs(p), abs(pitch), delta=3, msg=f"pitch {pitch}")

    def test_ema_smooths(self):
        e = signals.EMA(0.1)
        e.update(50)
        self.assertAlmostEqual(e.update(150), 60.0)


class TestFusion(unittest.TestCase):
    def test_baseline_gives_50(self):
        w = config.load_weights("exam")
        self.assertAlmostEqual(fusion.fuse({k: 1.0 for k in fusion.SIGNALS}, w), 50.0)

    def test_clipping_limits_spikes(self):
        w = config.load_weights()
        self.assertLessEqual(fusion.fuse({"fatigue": 1, "distraction": 1, "stress": 100}, w),
                             50 * config.SIGNAL_CLIP)

    def test_calibration_downweights_noisy_signal(self):
        rng = np.random.default_rng(0)
        w = fusion.calibrate_weights(1 + 0.1 * rng.standard_normal(500), 1 + 0.1 * rng.standard_normal(500),
                                     1 + 1.0 * rng.standard_normal(500), prior={"fatigue": 1, "distraction": 1, "stress": 1})
        self.assertLess(w["stress"], w["fatigue"])
        self.assertAlmostEqual(sum(w.values()), 1.0)

    def test_modes_bias_weights(self):
        ex, iv = config.load_weights("exam"), config.load_weights("interview")
        self.assertGreater(ex["distraction"], iv["distraction"])
        self.assertGreater(iv["stress"], ex["stress"])

    def test_reliability_drops_when_head_turned(self):
        self.assertLess(fusion.frame_reliability(40, 0, 150)["distraction"],
                        fusion.frame_reliability(0, 0, 150)["distraction"])


class TestPipelineValidation(unittest.TestCase):
    """Behavioural validation: the index and events must respond in the expected direction."""

    def run_session(self, mode, scenario, seconds=40, fps=30, cal=20):
        p = CognitivePipeline(mode, calibration_time=cal)
        rng = np.random.default_rng(1)
        out = []
        for i in range(seconds * fps):
            t = i / fps
            calm = t < cal
            kw = {"offset": tuple(rng.normal(0, 0.3, 2))}
            if i % 90 == 0:
                kw["eye_open"] = 0.1                               # normal blinking
            if not calm and scenario == "turn_away":
                kw["yaw"] = 40
            if not calm and scenario == "restless":
                kw["offset"] = tuple(rng.normal(0, 6, 2))
                kw["yaw"] = rng.normal(0, 6)
            if not calm and scenario == "rapid_blink" and i % 6 == 0:
                kw["eye_open"] = 0.1
            if not calm and scenario == "no_face":
                p.no_face(t)
                continue
            r = p.process(synthetic_face(**kw), W, H, t)
            if not r["calibrating"]:
                out.append(r["CognitiveLoad"])
        return p, np.array(out)

    def test_calm_session_stays_near_baseline(self):
        p, cli = self.run_session("exam", "calm")
        self.assertTrue(40 <= cli.mean() <= 60, cli.mean())
        self.assertEqual(len(p.events), 0)

    def test_restless_raises_cli(self):
        _, calm = self.run_session("interview", "calm")
        _, rest = self.run_session("interview", "restless")
        self.assertGreater(rest[-60:].mean(), calm[-60:].mean() + 10)

    def test_rapid_blinking_raises_cli(self):
        _, calm = self.run_session("interview", "calm")
        _, fast = self.run_session("interview", "rapid_blink")
        self.assertGreater(fast[-60:].mean(), calm[-60:].mean())

    def test_exam_turn_away_event(self):
        p, _ = self.run_session("exam", "turn_away")
        self.assertTrue(any("Looking away" in e[1] for e in p.events), p.events)
        self.assertLess(p.attention_pct, 50)

    def test_interview_eye_contact_event(self):
        p, _ = self.run_session("interview", "turn_away")
        self.assertTrue(any("eye contact" in e[1] for e in p.events), p.events)

    def test_no_face_event(self):
        p, _ = self.run_session("exam", "no_face")
        self.assertTrue(any("left frame" in e[1] for e in p.events))


if __name__ == "__main__":
    unittest.main()
